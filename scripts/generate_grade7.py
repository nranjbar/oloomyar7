def step(kind, prompt, answer, hint1, hint2, explanation, **fields):
    return dict(kind=kind,prompt=prompt,answer=answer,hint1=hint1,hint2=hint2,explanation=explanation,**fields)

def single(prompt, good, bad, hint1, hint2, explanation, source_options=None, correct_index=None):
    opts = source_options or [good] + bad
    if source_options is None:
        random.Random(prompt).shuffle(opts)
    flags = [i==correct_index if source_options is not None else x==good for i,x in enumerate(opts)]
    return step('single',prompt,good,hint1,hint2,explanation,options=[dict(text=t,correct=c) for t,c in zip(opts,flags)])

def multi(prompt, good, bad, pick, hint1, hint2, explanation):
    opts=good+bad
    random.Random(prompt).shuffle(opts)
    return step('multi',prompt,'؛ '.join(good),hint1,hint2,explanation,pick=pick,options=[dict(text=t,correct=t in good) for t in opts])

def match(prompt, rows, choices, hint1, hint2, explanation):
    pairs=[]
    for row in rows:
        left,right,*local = row
        pair=dict(left=left,right=right)
        if local: pair['choices']=local[0]
        pairs.append(pair)
    return step('match',prompt,'\n'.join(f'{i+1}) {p["left"]}: {p["right"]}' for i,p in enumerate(pairs)),hint1,hint2,explanation,pairs=pairs,choices=choices)

def order(prompt, items, hint1, hint2, explanation):
    return step('order',prompt,' ← '.join(items),hint1,hint2,explanation,items=items,correctOrder=list(range(len(items))))

