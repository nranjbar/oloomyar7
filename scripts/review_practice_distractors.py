def protected_content(chapters):
    """Everything except generated wrong labels and row choice banks."""
    result = copy.deepcopy(chapters)
    for qs in result.values():
        for q in qs:
            if q['section'] == 'چهارگزینه‌ای' or q['sourceNumber'] == 1:
                continue  # Including every original printed option/bank.
            for s in q['steps']:
                for pair in s.get('pairs', []):
                    pair.pop('choices', None)
                for option in s.get('options', []):
                    if not option['correct'] and q['section'] != 'چهارگزینه‌ای':
                        option['text'] = '<authored distractor>'
    return result


